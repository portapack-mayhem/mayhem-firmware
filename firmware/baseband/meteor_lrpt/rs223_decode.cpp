constexpr int kNn = 255;
constexpr int kNroots = 32;
constexpr int kPad = 0;
constexpr int kFcr = 112;
constexpr int kPrim = 11;
constexpr int kIprim = 116;
constexpr int kA0 = kNn;
constexpr int kNoEras = 0;

static inline int modnn255(int x) {
    while (x >= kNn) {
        x -= kNn;
        x = (x >> 8) + (x & 255);
    }
    return x;
}

/* Phil Karn DECODE_RS (decode_rs.h), pad=0, no erasures. Returns -1 if uncorrectable, else 0. */
static int decode_rs255_inplace(uint8_t* data) {
    int deg_lambda = 0, el = 0, deg_omega = 0;
    int i = 0, j = 0, r = 0, k = 0;
    uint8_t q = 0, tmp = 0, num1 = 0, num2 = 0, den = 0, discr_r = 0;
    std::array<uint8_t, kNroots + 1> lambda{};
    std::array<uint8_t, kNroots> s{};
    std::array<uint8_t, kNroots + 1> b{};
    std::array<uint8_t, kNroots + 1> t{};
    std::array<uint8_t, kNroots + 1> omega{};
    std::array<uint8_t, kNroots> root{};
    std::array<uint8_t, kNroots + 1> reg{};
    std::array<uint8_t, kNroots> loc{};
    int syn_error = 0;
    int count = 0;

    for (i = 0; i < kNroots; i++)
        s[(size_t)i] = data[0];

    for (j = 1; j < kNn - kPad; j++) {
        for (i = 0; i < kNroots; i++) {
            if (s[(size_t)i] == 0) {
                s[(size_t)i] = data[j];
            } else {
                s[(size_t)i] = data[j] ^ kAlphaTo[modnn255((int)kIndexOf[s[(size_t)i]] + (kFcr + i) * kPrim)];
            }
        }
    }

    syn_error = 0;
    for (i = 0; i < kNroots; i++) {
        syn_error |= s[(size_t)i];
        s[(size_t)i] = kIndexOf[s[(size_t)i]];
    }

    if (!syn_error)
        return 0;

    lambda.fill(0);
    lambda[0] = 1;

    for (i = 0; i < kNroots + 1; i++)
        b[(size_t)i] = kIndexOf[lambda[(size_t)i]];

    r = kNoEras;
    el = kNoEras;
    while (++r <= kNroots) {
        discr_r = 0;
        for (i = 0; i < r; i++) {
            if ((lambda[(size_t)i] != 0) && (s[(size_t)(r - i - 1)] != kA0)) {
                discr_r ^= kAlphaTo[modnn255((int)kIndexOf[lambda[(size_t)i]] + (int)s[(size_t)(r - i - 1)])];
            }
        }
        discr_r = kIndexOf[discr_r];
        if (discr_r == kA0) {
            std::memmove(&b[1], &b[0], kNroots * sizeof(b[0]));
            b[0] = (uint8_t)kA0;
        } else {
            t[0] = lambda[0];
            for (i = 0; i < kNroots; i++) {
                if (b[(size_t)i] != kA0)
                    t[(size_t)i + 1] = lambda[(size_t)i + 1] ^ kAlphaTo[modnn255((int)discr_r + (int)b[(size_t)i])];
                else
                    t[(size_t)i + 1] = lambda[(size_t)i + 1];
            }
            if (2 * el <= r + kNoEras - 1) {
                el = r + kNoEras - el;
                for (i = 0; i <= kNroots; i++)
                    b[(size_t)i] = (lambda[(size_t)i] == 0) ? (uint8_t)kA0 : (uint8_t)modnn255((int)kIndexOf[lambda[(size_t)i]] - (int)discr_r + kNn);
            } else {
                std::memmove(&b[1], &b[0], kNroots * sizeof(b[0]));
                b[0] = (uint8_t)kA0;
            }
            std::memcpy(lambda.data(), t.data(), (kNroots + 1) * sizeof(t[0]));
        }
    }

    deg_lambda = 0;
    for (i = 0; i < kNroots + 1; i++) {
        lambda[(size_t)i] = kIndexOf[lambda[(size_t)i]];
        if (lambda[(size_t)i] != kA0)
            deg_lambda = i;
    }

    std::memcpy(&reg[1], &lambda[1], kNroots * sizeof(reg[0]));
    count = 0;
    for (i = 1, k = kIprim - 1; i <= kNn; i++, k = modnn255(k + kIprim)) {
        q = 1;
        for (j = deg_lambda; j > 0; j--) {
            if (reg[(size_t)j] != kA0) {
                reg[(size_t)j] = (uint8_t)modnn255((int)reg[(size_t)j] + j);
                q ^= kAlphaTo[reg[(size_t)j]];
            }
        }
        if (q != 0)
            continue;
        root[(size_t)count] = (uint8_t)i;
        loc[(size_t)count] = (uint8_t)k;
        if (++count == deg_lambda)
            break;
    }
    if (deg_lambda != count)
        return -1;

    deg_omega = deg_lambda - 1;
    for (i = 0; i <= deg_omega; i++) {
        tmp = 0;
        for (j = i; j >= 0; j--) {
            if ((s[(size_t)(i - j)] != kA0) && (lambda[(size_t)j] != kA0))
                tmp ^= kAlphaTo[modnn255((int)s[(size_t)(i - j)] + (int)lambda[(size_t)j])];
        }
        omega[(size_t)i] = kIndexOf[tmp];
    }

    for (j = count - 1; j >= 0; j--) {
        num1 = 0;
        for (i = deg_omega; i >= 0; i--) {
            if (omega[(size_t)i] != kA0)
                num1 ^= kAlphaTo[modnn255((int)omega[(size_t)i] + i * (int)root[(size_t)j])];
        }
        num2 = kAlphaTo[modnn255((int)root[(size_t)j] * (kFcr - 1) + kNn)];
        den = 0;
        for (i = std::min(deg_lambda, kNroots - 1) & ~1; i >= 0; i -= 2) {
            if (lambda[(size_t)(i + 1)] != kA0)
                den ^= kAlphaTo[modnn255((int)lambda[(size_t)(i + 1)] + i * (int)root[(size_t)j])];
        }
        if (num1 != 0 && loc[(size_t)j] >= kPad) {
            data[loc[(size_t)j] - kPad] ^= kAlphaTo[modnn255((int)kIndexOf[num1] + (int)kIndexOf[num2] + kNn - (int)kIndexOf[den])];
        }
    }
    return count;
}

static void deinterleave4(const uint8_t* data, uint8_t* out, int pos) {
    for (int ii = 0; ii < 255; ii++)
        out[ii] = data[ii * 4 + pos];
}

static void interleave4(const uint8_t* in, uint8_t* data, int pos) {
    for (int ii = 0; ii < 255; ii++)
        data[ii * 4 + pos] = in[ii];
}

