bool meteor_lrpt_rs_decode_interleaved_depth4(uint8_t* body1020, int16_t* errors_out4) {
    std::array<uint8_t, 255> buff{};
    std::array<uint8_t, 255> saved{};
    bool all_ok = true;

    for (int b = 0; b < 4; b++) {
        deinterleave4(body1020, buff.data(), b);
        std::memcpy(saved.data(), buff.data(), 255);
        const int dec = decode_rs255_inplace(buff.data());
        if (dec < 0) {
            errors_out4[b] = -1;
            interleave4(saved.data(), body1020, b);
            all_ok = false;
        } else {
            int fixes = 0;
            for (int i = 0; i < 223; i++) {
                if (buff[(size_t)i] != saved[(size_t)i])
                    fixes++;
            }
            errors_out4[b] = (int16_t)fixes;
            interleave4(buff.data(), body1020, b);
        }
    }
    return all_ok;
}
